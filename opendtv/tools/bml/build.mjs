/*
 * build.mjs - build the app's BML bundle from source.
 *
 *   node build.mjs              -> app/src/main/assets/bml/bml.js
 *   node build.mjs --out bml2.js -> a second copy under another name, leaving the shipped asset untouched
 *
 * Input:  host.js (our adapter) + vendor/web-bml (web-bml 3.0.1, public, pinned in engine.lock.json)
 * Output: one IIFE that the app's WebView loads, lowered to Chrome 55.
 *
 * Two passes, because of one syntax those WebViews cannot parse: the engine uses a regex lookbehind
 * (Chrome 62+), and esbuild will not lower it. The patterns are `(?<=\s*)` / `(?=\s*)`, which are
 * always true, so removing them leaves the regex equivalent - the same rewrite tools/build_bml.sh
 * has done since this asset was a hand-uploaded blob.
 */
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, '..', '..');
const args = process.argv.slice(2);
const outFlag = args.indexOf('--out');
const outName = outFlag >= 0 ? args[outFlag + 1] : 'bml.js';
const out = join(appRoot, 'app', 'src', 'main', 'assets', 'bml', outName);

const work = mkdtempSync(join(tmpdir(), 'bml-build-'));
try {
  const step1 = join(work, 'bundle.js');
  console.log('pass 1: bundle host.js + web-bml engine');
  buildSync({
    entryPoints: [join(here, 'host.js')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    logLevel: 'warning',
    outfile: step1,
  });

  console.log('pass 2: rewrite the one regex Chrome 55 cannot parse, then lower to chrome55');
  let text = readFileSync(step1, 'utf8');
  const before = text.length;
  // both spellings: escaped inside a string/regex source, and bare
  text = text.split('(?<=\\\\s*)').join('').split('(?=\\\\s*)').join('');
  text = text.split('(?<=\\s*)').join('').split('(?=\\s*)').join('');
  const step2 = join(work, 'lowered.js');
  writeFileSync(step2, text, 'utf8');
  if (text.length !== before) console.log(`  rewrote ${before - text.length} bytes of lookbehind`);

  buildSync({
    entryPoints: [step2],
    bundle: false,
    target: 'chrome55',
    logLevel: 'warning',
    outfile: out,
  });

  const size = statSync(out).size;
  console.log(`built ${outName}: ${size.toLocaleString()} B`);

  // A stamp on the first line, because a tester report cannot be attributed to an engine version
  // otherwise (beta session, 2026-11-04: the bundle carried no version string at all). Read from
  // engine.lock.json - the same file fetch-engine.mjs refuses a moved tag against - so the stamp
  // cannot drift from what was actually bundled. Deliberately NO timestamp: re-running this build
  // must reproduce the same asset byte for byte, or "the bundle matches its lock" becomes unprovable.
  // A comment is inert for the WebView.
  try {
    const lock = JSON.parse(readFileSync(join(here, 'engine.lock.json'), 'utf8'));
    const sha = String(lock.commit || '').slice(0, 7);
    const stamped = `//! OpenDTV BML bundle - web-bml ${lock.tag || '?'} @${sha} - generated by tools/bml/build.mjs\n`;
    const body = readFileSync(out, 'utf8');
    if (!body.startsWith('//! OpenDTV BML bundle')) {
      writeFileSync(out, stamped + body, 'utf8');
      console.log(`  stamped: ${stamped.trim()}`);
    }
  } catch (e) {
    console.warn(`  could not stamp the bundle (${e.message}) - it still builds, but a report cannot name the engine`);
  }

  if (/\(\?<[=!]/.test(readFileSync(out, 'utf8'))) {
    console.error('WARNING: a regex lookbehind survived - old WebViews cannot parse this');
    process.exitCode = 1;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
